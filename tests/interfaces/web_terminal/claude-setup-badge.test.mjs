import { createScaffoldGalleryDetail } from '../../../src/osprey/interfaces/web_terminal/static/js/scaffold/detail.js';
import { createScaffoldGalleryDetailContent } from '../../../src/osprey/interfaces/web_terminal/static/js/scaffold/detail-content.js';
import { createScaffoldGalleryEditForm } from '../../../src/osprey/interfaces/web_terminal/static/js/scaffold/edit-form.js';
import { createScaffoldGalleryEdit } from '../../../src/osprey/interfaces/web_terminal/static/js/scaffold/edit.js';

/** A reserved artifact: the build profile renders it, so the panel cannot save it. */
const RESERVED = {
  name: 'settings-json',
  category: 'config',
  status: 'framework',
  output_path: '.claude/settings.json',
  language: 'json',
  read_only: true,
};

/** An ordinary artifact the panel may write. */
const WRITABLE = {
  name: 'reviewer',
  category: 'agents',
  status: 'user-owned',
  output_path: '.claude/agents/reviewer.md',
  language: 'markdown',
  read_only: false,
};

/**
 * The 403 detail `PUT /api/scaffold/{name}/override` answers with for a
 * reserved artifact: ProtectedArtifactError's message, built by
 * `_refuse_reserved` (scaffold_gallery_service.py) from the canonical name and
 * the channel table, and passed through by the route as `detail=str(e)`. The
 * channel text is `.claude/settings.json`'s entry in RESERVED_PROJECT_PATHS.
 */
const REFUSAL_DETAIL =
  "'settings-json' belongs to the profile's `config:` keys "
  + '(`claude_code.permissions`, `claude_code.hooks`, `artifacts.hooks`). '
  + 'NOTHING WAS WRITTEN.';

/**
 * What a refused claim answers with instead: `scaffold_override` raises
 * ScaffoldClaimError, which the app-level handler renders as a 409 -- a
 * different status and a different message from the save refusal above, but
 * the same trip through `apiRequest` into the banner.
 */
const CLAIM_REFUSAL_DETAIL =
  "'settings-json' is generated by the framework render — carry the change as "
  + 'a `config:` key instead.';

/**
 * The transitional payload: an artifact as the service serves it today, with
 * no `read_only` key at all. Absent must read as writable.
 * @param {any} artifact
 * @returns {any}
 */
function withoutReadOnlyKey(artifact) {
  const copy = { ...artifact };
  delete copy.read_only;
  return copy;
}

/** @param {Partial<any>} [overrides] */
function makeDetailGallery(overrides = {}) {
  return /** @type {any} */ ({
    selectedArtifact: null,
    currentView: 'gallery',
    detailMode: 'preview',
    editDirty: false,
    artifacts: [],
    galleryView: document.createElement('div'),
    detailView: document.createElement('div'),
    detailHeaderEl: document.createElement('div'),
    detailModesEl: document.createElement('div'),
    detailContentEl: document.createElement('div'),
    onDetailOpen: null,
    load: () => Promise.resolve(),
    renderDetailModes: () => {},
    closeDetail: vi.fn(),
    releaseToFramework: vi.fn(),
    takeOwnership: vi.fn(),
    handleEditFramework: vi.fn(),
    discardEdits: vi.fn(),
    saveOverride: vi.fn(),
    renderEdit: vi.fn(() => Promise.resolve()),
    ...overrides,
  });
}

/**
 * Render one artifact's card into a fresh section element.
 * @param {any} artifact
 * @param {string} [cat]
 * @returns {HTMLElement}
 */
function renderCard(artifact, cat = 'agents') {
  const section = document.createElement('div');
  const { renderArtifactCard } = createScaffoldGalleryCards({ openDetail: vi.fn() });
  renderArtifactCard(section, artifact, cat);
  return /** @type {HTMLElement} */ (section.firstElementChild);
}

/**
 * Open an artifact's detail view and return the gallery host, with
 * renderDetailModes wired to the factory's own so mode re-renders are real
 * (the same delegation ArtifactGallery does).
 * @param {any} artifact
 */
function openDetail(artifact) {
  const gallery = makeDetailGallery({ selectedArtifact: artifact });
  const detail = createScaffoldGalleryDetail(gallery);
  gallery.renderDetailModes = detail.renderDetailModes;
  gallery.detailHeaderEl.className = 'prompts-detail-header';
  detail.openDetail(artifact);
  return { gallery, detail };
}

