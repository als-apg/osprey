/**
 * Unit tests for the scaffold gallery's protected-set (read-only) affordances:
 *   npx vitest run tests/interfaces/web_terminal/claude-setup-badge.test.mjs
 *
 * The gallery is the panel an operator actually opens to read and edit the
 * agent's setup files, and some of those files are now reserved: the write
 * gates refuse a save, a claim, or a delete aimed at them and answer 403 with
 * the channel that owns the change instead. An artifact carrying
 * `read_only: true` is that same verdict, precomputed at list time.
 *
 * These tests pin the client's half of that contract:
 *   - the badge, on the card and in the detail header, so the fact is met
 *     while reading rather than only when a save comes back refused;
 *   - the controls that would attempt a refused write (Edit, Save, the
 *     ownership button) rendered disabled, and the editors rendered
 *     un-typeable -- including settings.json, whose Preview offers no
 *     editable control at all;
 *   - the panel copy that says what to do instead of saving here;
 *   - and, because the server is the enforcement and the client only mirrors
 *     it, the 403 refusal detail reaching the error banner verbatim when a
 *     write goes out anyway.
 *
 * Fake `gallery` host objects stand in for the ArtifactGallery instance --
 * the same "pass `this`" shape the real class uses -- mirroring
 * scaffold-detail.test.mjs and scaffold-edit.test.mjs.
 *
 * NOTE: imported by RELATIVE path -- these modules live under web_terminal,
 * not design-system, so the `/design-system/js/*` alias does not apply.
 */

