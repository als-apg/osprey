"""Tests for the bundle asset rules: which file an image target names, and what it is.

Every picture here is built at test time; only leading bytes matter, because the
lookup decides a type from them and never decodes.
"""

from __future__ import annotations

import io
from pathlib import Path

import pytest
from PIL import Image

from osprey.services.facility_knowledge.okf import assets
from osprey.services.facility_knowledge.okf.assets import (
    AGENT_IMAGE_TYPES,
    ASSET_ERROR_CODES,
    MAX_IMAGE_BYTES,
    PANEL_IMAGE_TYPES,
    Asset,
    AssetError,
    concept_dir,
    lookup_asset,
    resolve_image_target,
)

_CONCEPT = "---\ntype: Device\ntitle: BPM\n---\n\nBody.\n"


def _write(path: Path, data: bytes | str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(data, str):
        path.write_text(data, encoding="utf-8")
    else:
        path.write_bytes(data)
    return path


def _picture(fmt: str) -> bytes:
    buf = io.BytesIO()
    Image.new("RGB", (4, 3), (200, 10, 10)).save(buf, format=fmt)
    return buf.getvalue()


_SVG = b'<svg xmlns="http://www.w3.org/2000/svg" width="4" height="4"/>'
# An ISO-BMFF header with the AVIF brand: what an .avif file opens with.
_AVIF_HEAD = b"\x00\x00\x00\x1cftypavif\x00\x00\x00\x00avifmif1miaf" + b"\x00" * 64


def _code(root: Path, bundle_path: str) -> str:
    with pytest.raises(AssetError) as info:
        lookup_asset(root, bundle_path)
    return info.value.code


class TestConstants:
    def test_limit_is_ten_mebibytes(self) -> None:
        assert MAX_IMAGE_BYTES == 10 * 1024 * 1024

    def test_panel_and_agent_types(self) -> None:
        assert PANEL_IMAGE_TYPES == frozenset({"png", "jpeg", "gif", "webp", "svg"})
        assert AGENT_IMAGE_TYPES == PANEL_IMAGE_TYPES - {"svg"}

    def test_error_codes(self) -> None:
        assert ASSET_ERROR_CODES == frozenset(
            {
                "outside_bundle",
                "dot_path",
                "symlink_escape",
                "not_found",
                "not_an_image",
                "disallowed_type",
                "too_large",
            }
        )

    def test_error_refuses_an_unknown_code(self) -> None:
        with pytest.raises(ValueError):
            AssetError("nope")

    def test_package_reexports(self) -> None:
        from osprey.services.facility_knowledge import okf

        for name in assets.__all__:
            assert getattr(okf, name) is getattr(assets, name)
            assert name in okf.__all__


class TestLookupTypes:
    @pytest.mark.parametrize(
        ("fmt", "kind", "mime"),
        [
            ("PNG", "png", "image/png"),
            ("JPEG", "jpeg", "image/jpeg"),
            ("GIF", "gif", "image/gif"),
            ("WEBP", "webp", "image/webp"),
        ],
    )
    def test_each_raster_type(self, tmp_path: Path, fmt: str, kind: str, mime: str) -> None:
        data = _picture(fmt)
        _write(tmp_path / "figures" / "pic.bin", data)

        found = lookup_asset(tmp_path, "figures/pic.bin")

        assert found == Asset(
            path=(tmp_path / "figures" / "pic.bin").resolve(),
            type=kind,
            mime=mime,
            size=len(data),
        )

    def test_svg(self, tmp_path: Path) -> None:
        _write(tmp_path / "a.svg", _SVG)

        found = lookup_asset(tmp_path, "a.svg")

        assert (found.type, found.mime, found.size) == ("svg", "image/svg+xml", len(_SVG))

    @pytest.mark.parametrize(
        "prefix",
        [
            b'<?xml version="1.0" encoding="UTF-8"?>\n',
            b"<!-- Generated by a plotting tool, version 3.9 -->\n",
            b"\xef\xbb\xbf  \n",
            b'<?xml version="1.0"?>\n<!-- c1 -->\n<!-- c2 -->\n'
            b'<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" '
            b'"http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">\n',
            b'<!DOCTYPE svg [\n  <!ENTITY ns "http://www.w3.org/2000/svg">\n]>\n',
        ],
    )
    def test_svg_after_declaration_comment_bom_or_doctype(
        self, tmp_path: Path, prefix: bytes
    ) -> None:
        _write(tmp_path / "plot.svg", prefix + _SVG)

        assert lookup_asset(tmp_path, "plot.svg").type == "svg"

    def test_svg_type_comes_from_bytes_not_name(self, tmp_path: Path) -> None:
        _write(tmp_path / "plot.png", _SVG)

        assert lookup_asset(tmp_path, "plot.png").type == "svg"

    @pytest.mark.parametrize(
        "data",
        [
            b'<?xml version="1.0"?>\n<feed xmlns="http://www.w3.org/2005/Atom"/>',
            b"<!-- an svg in a comment: <svg> -->\n<html><body/></html>",
            b"<svgx/>",
            b"<!-- never closed <svg/>",
        ],
    )
    def test_other_xml_is_not_an_image(self, tmp_path: Path, data: bytes) -> None:
        _write(tmp_path / "x.svg", data)

        assert _code(tmp_path, "x.svg") == "not_an_image"

    def test_text_named_png_is_not_an_image(self, tmp_path: Path) -> None:
        _write(tmp_path / "fake.png", "This is a note, not a picture.\n")

        assert _code(tmp_path, "fake.png") == "not_an_image"

    def test_pdf_is_not_an_image(self, tmp_path: Path) -> None:
        _write(tmp_path / "doc.png", b"%PDF-1.7\n" + b"\x00" * 64)

        assert _code(tmp_path, "doc.png") == "not_an_image"

    def test_empty_file_is_not_an_image(self, tmp_path: Path) -> None:
        _write(tmp_path / "empty.png", b"")

        assert _code(tmp_path, "empty.png") == "not_an_image"

    def test_bmp_is_disallowed(self, tmp_path: Path) -> None:
        _write(tmp_path / "pic.bmp", _picture("BMP"))

        assert _code(tmp_path, "pic.bmp") == "disallowed_type"

    def test_tiff_is_disallowed(self, tmp_path: Path) -> None:
        _write(tmp_path / "pic.tif", _picture("TIFF"))

        assert _code(tmp_path, "pic.tif") == "disallowed_type"

    def test_avif_header_is_disallowed(self, tmp_path: Path) -> None:
        _write(tmp_path / "pic.avif", _AVIF_HEAD)

        assert _code(tmp_path, "pic.avif") == "disallowed_type"

    def test_no_decoder_is_called(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
        _write(tmp_path / "a.png", _picture("PNG"))

        def _boom(*_a: object, **_k: object) -> None:
            raise AssertionError("an image decoder was called")

        monkeypatch.setattr(Image, "open", _boom)

        assert lookup_asset(tmp_path, "a.png").type == "png"


class TestLookupSize:
    def test_at_the_limit_is_accepted(self, tmp_path: Path) -> None:
        head = _picture("PNG")
        _write(tmp_path / "big.png", head + b"\x00" * (MAX_IMAGE_BYTES - len(head)))

        assert lookup_asset(tmp_path, "big.png").size == MAX_IMAGE_BYTES

    def test_one_byte_over_the_limit(self, tmp_path: Path) -> None:
        head = _picture("PNG")
        _write(tmp_path / "big.png", head + b"\x00" * (MAX_IMAGE_BYTES + 1 - len(head)))

        assert _code(tmp_path, "big.png") == "too_large"


class TestLookupContainment:
    def test_missing_file(self, tmp_path: Path) -> None:
        assert _code(tmp_path, "figures/none.png") == "not_found"

    def test_directory_is_not_found(self, tmp_path: Path) -> None:
        (tmp_path / "figures").mkdir()

        assert _code(tmp_path, "figures") == "not_found"

    def test_leading_slash_is_root_relative(self, tmp_path: Path) -> None:
        _write(tmp_path / "a.png", _picture("PNG"))

        assert lookup_asset(tmp_path, "/a.png").type == "png"

    @pytest.mark.parametrize("path", ["../secret.png", "figures/../../secret.png", ".."])
    def test_dot_dot_escape(self, tmp_path: Path, path: str) -> None:
        root = tmp_path / "bundle"
        root.mkdir()
        _write(tmp_path / "secret.png", _picture("PNG"))

        assert _code(root, path) == "outside_bundle"

    def test_percent_encoding_is_not_decoded_by_the_lookup(self, tmp_path: Path) -> None:
        root = tmp_path / "bundle"
        root.mkdir()
        _write(tmp_path / "secret.png", _picture("PNG"))

        assert _code(root, "%2e%2e/secret.png") == "not_found"

    @pytest.mark.parametrize("path", [".hidden.png", ".git/x.png", "figures/.cache/x.png"])
    def test_dot_path(self, tmp_path: Path, path: str) -> None:
        _write(tmp_path / path, _picture("PNG"))

        assert _code(tmp_path, path) == "dot_path"

    def test_symlink_out_of_the_root(self, tmp_path: Path) -> None:
        outside = _write(tmp_path / "outside" / "secret.png", _picture("PNG"))
        root = tmp_path / "bundle"
        root.mkdir()
        (root / "leak.png").symlink_to(outside)

        assert _code(root, "leak.png") == "symlink_escape"

    def test_symlinked_directory_out_of_the_root(self, tmp_path: Path) -> None:
        _write(tmp_path / "outside" / "secret.png", _picture("PNG"))
        root = tmp_path / "bundle"
        root.mkdir()
        (root / "figures").symlink_to(tmp_path / "outside", target_is_directory=True)

        assert _code(root, "figures/secret.png") == "symlink_escape"

    def test_symlink_into_a_dot_path_inside_the_root(self, tmp_path: Path) -> None:
        hidden = _write(tmp_path / ".private" / "x.png", _picture("PNG"))
        (tmp_path / "alias.png").symlink_to(hidden)

        assert _code(tmp_path, "alias.png") == "dot_path"

    def test_symlink_inside_the_root_is_followed(self, tmp_path: Path) -> None:
        real = _write(tmp_path / "figures" / "real.png", _picture("PNG"))
        (tmp_path / "alias.png").symlink_to(real)

        found = lookup_asset(tmp_path, "alias.png")

        assert (found.type, found.path) == ("png", real.resolve())

    def test_root_reached_through_a_symlink(self, tmp_path: Path) -> None:
        real_root = tmp_path / "real"
        _write(real_root / "a.png", _picture("PNG"))
        link_root = tmp_path / "link"
        link_root.symlink_to(real_root, target_is_directory=True)

        assert lookup_asset(link_root, "a.png").type == "png"


class TestResolveImageTarget:
    @pytest.mark.parametrize(
        ("target", "source_dir", "expected"),
        [
            ("/figures/a.png", "devices", "figures/a.png"),
            ("figures/a.png", "devices", "devices/figures/a.png"),
            ("a.png", "", "a.png"),
            ("./a.png", "devices", "devices/a.png"),
            ("../figures/a.png", "devices/sub", "devices/figures/a.png"),
            ("../a.png", "devices", "a.png"),
            ("figures/my%20plot.png", "devices", "devices/figures/my plot.png"),
            ("a.png#frag", "devices", "devices/a.png"),
            ("a.png?v=2", "devices", "devices/a.png"),
            ("  a.png  ", "devices", "devices/a.png"),
        ],
    )
    def test_in_bundle_targets(self, target: str, source_dir: str, expected: str) -> None:
        assert resolve_image_target(target, source_dir) == expected

    @pytest.mark.parametrize(
        "target",
        [
            "https://example.org/a.png",
            "http://example.org/a.png",
            "data:image/png;base64,iVBORw0KGgo=",
            "DATA:image/png;base64,iVBORw0KGgo=",
            "mailto:someone@example.org",
            "//cdn.example.org/a.png",
            "//a.png",
            "#only-a-fragment",
            "",
            "   ",
        ],
    )
    def test_external_targets(self, target: str) -> None:
        assert resolve_image_target(target, "devices") is None

    @pytest.mark.parametrize(
        ("target", "source_dir"),
        [
            ("../a.png", ""),
            ("../../a.png", "devices"),
            ("figures/../../../a.png", "devices"),
            ("%2e%2e/a.png", ""),
            ("..%2F..%2Fa.png", "devices"),
            ("/../a.png", "devices"),
        ],
    )
    def test_escape_raises_outside_bundle(self, target: str, source_dir: str) -> None:
        with pytest.raises(AssetError) as info:
            resolve_image_target(target, source_dir)

        assert info.value.code == "outside_bundle"

    def test_resolver_touches_no_file(self) -> None:
        assert resolve_image_target("nowhere/x.png", "devices") == "devices/nowhere/x.png"

    def test_dot_path_target_resolves_to_a_dot_path_lookup(self, tmp_path: Path) -> None:
        _write(tmp_path / "devices" / ".hidden" / "x.png", _picture("PNG"))

        resolved = resolve_image_target(".hidden/x.png", "devices")

        assert resolved == "devices/.hidden/x.png"
        assert _code(tmp_path, resolved) == "dot_path"

    def test_resolved_target_feeds_the_lookup(self, tmp_path: Path) -> None:
        _write(tmp_path / "devices" / "figures" / "my plot.png", _picture("PNG"))

        resolved = resolve_image_target("figures/my%20plot.png", "devices")

        assert resolved is not None
        assert lookup_asset(tmp_path, resolved).type == "png"


class TestConceptDir:
    def test_leading_slash_and_plain_id_agree(self, tmp_path: Path) -> None:
        _write(tmp_path / "devices" / "bpm.md", _CONCEPT)

        assert concept_dir(tmp_path, "/devices/bpm") == "devices"
        assert concept_dir(tmp_path, "devices/bpm") == "devices"

    def test_top_level_concept(self, tmp_path: Path) -> None:
        _write(tmp_path / "overview.md", _CONCEPT)

        assert concept_dir(tmp_path, "overview") == ""

    def test_empty_id_is_the_root(self, tmp_path: Path) -> None:
        assert concept_dir(tmp_path, "") == ""

    def test_symlinked_concept_resolves_from_its_id(self, tmp_path: Path) -> None:
        real = _write(tmp_path / "library" / "pump.md", _CONCEPT)
        (tmp_path / "devices").mkdir()
        (tmp_path / "devices" / "pump.md").symlink_to(real)

        assert concept_dir(tmp_path, "devices/pump") == "devices"

    @pytest.mark.parametrize("concept_id", ["devices/none", "/devices/none", "devices"])
    def test_id_naming_no_concept(self, tmp_path: Path, concept_id: str) -> None:
        _write(tmp_path / "devices" / "bpm.md", _CONCEPT)

        with pytest.raises(AssetError) as info:
            concept_dir(tmp_path, concept_id)

        assert info.value.code == "outside_bundle"

    @pytest.mark.parametrize("concept_id", ["../outside/x", ".git/x", "devices/../../x"])
    def test_id_leaving_the_root_or_in_a_dot_path(self, tmp_path: Path, concept_id: str) -> None:
        root = tmp_path / "bundle"
        _write(tmp_path / "outside" / "x.md", _CONCEPT)
        _write(root / ".git" / "x.md", _CONCEPT)
        _write(tmp_path / "x.md", _CONCEPT)

        with pytest.raises(AssetError) as info:
            concept_dir(root, concept_id)

        assert info.value.code == "outside_bundle"

    def test_concept_symlinked_out_of_the_root(self, tmp_path: Path) -> None:
        outside = _write(tmp_path / "outside" / "x.md", _CONCEPT)
        root = tmp_path / "bundle"
        (root / "devices").mkdir(parents=True)
        (root / "devices" / "x.md").symlink_to(outside)

        with pytest.raises(AssetError) as info:
            concept_dir(root, "devices/x")

        assert info.value.code == "outside_bundle"
