def _centre(node: dict) -> tuple[float, float]:
    g = node["geometry"]
    return g["x"] + g["width"] / 2, g["y"] + g["height"] / 2


def _corners(node: dict) -> list[tuple[float, float]]:
    """The four corners of a node's box, turned by its ``rotation`` about its centre."""
    g = node["geometry"]
    cx, cy = _centre(node)
    a = math.radians(node["props"].get("rotation", 0))
    out = []
    for dx in (-g["width"] / 2, g["width"] / 2):
        for dy in (-g["height"] / 2, g["height"] / 2):
            out.append(
                (cx + dx * math.cos(a) - dy * math.sin(a), cy + dx * math.sin(a) + dy * math.cos(a))
            )
    return out


def _outline(node: dict, step: float = 2.0) -> list[tuple[float, float]]:
    """Points on a shape's outline as drawn, ``step`` px apart or less."""
    if node["type"] == "ellipse":
        g = node["geometry"]
        cx, cy = _centre(node)
        n = math.ceil(math.pi * max(g["width"], g["height"]) / step)
        return [
            (
                cx + g["width"] / 2 * math.cos(2 * math.pi * i / n),
                cy + g["height"] / 2 * math.sin(2 * math.pi * i / n),
            )
            for i in range(n)
        ]
    a, b, d, c = _corners(node)  # (-,-) (-,+) (+,-) (+,+)
    out = []
    for p, q in ((a, d), (d, c), (c, b), (b, a)):
        n = max(1, math.ceil(math.dist(p, q) / step))
        out += [(p[0] + (q[0] - p[0]) * i / n, p[1] + (q[1] - p[1]) * i / n) for i in range(n)]
    return out


def _meet(a: dict, b: dict) -> bool:
    """Whether two convex shapes share a point."""
    return any(_holds(b, p) for p in _outline(a)) or any(_holds(a, p) for p in _outline(b))


def _bounds(node: dict) -> dict:
    """The upright box that holds a node as drawn (turned by its rotation)."""
    xs, ys = zip(*_corners(node), strict=True)
    return {
        "geometry": {
            "x": min(xs),
            "y": min(ys),
            "width": max(xs) - min(xs),
            "height": max(ys) - min(ys),
        }
    }


def _holds(area: dict, point: tuple[float, float]) -> bool:
    """Whether ``point`` lies inside the area's shape as the runtime turns it."""
    g = area["geometry"]
    cx, cy = _centre(area)
    if area["type"] == "ellipse":
        return (
            math.hypot((point[0] - cx) / (g["width"] / 2), (point[1] - cy) / (g["height"] / 2)) <= 1
        )
    a = -math.radians(area["props"].get("rotation", 0))
    dx, dy = point[0] - cx, point[1] - cy
    u, v = dx * math.cos(a) - dy * math.sin(a), dx * math.sin(a) + dy * math.cos(a)
    return abs(u) <= g["width"] / 2 and abs(v) <= g["height"] / 2


