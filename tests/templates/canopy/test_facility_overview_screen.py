def _tokens(expression: str, bound: dict[str, str]) -> list[re.Match]:
    """Each bound input in ``expression``: ``{N}`` tokens, or bare names (the authoring form)."""
    if "{" in expression:
        return list(TOKEN.finditer(expression))
    names = "|".join(re.escape(k) for k in sorted(bound, key=len, reverse=True))
    return list(re.finditer(rf"(?<![A-Za-z0-9_])({names})(?![A-Za-z0-9_])", expression))


