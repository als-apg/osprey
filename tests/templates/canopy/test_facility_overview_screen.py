def test_conditions_over_labelled_channels_use_the_labelled_input_form(
    nodes: list[dict], formulas: dict, channels: dict
) -> None:
    assert gen.LABELLED_INPUT_FORM == "index"
    expressions: list[tuple[str, dict[str, str]]] = []
    for n in nodes:
        for rule in n.get("rules", []):
            if "conditions" in rule:
                bound = {str(i): p["name"] for i, p in enumerate(rule["pvs"])}
                expressions += [(c["expression"], bound) for c in rule["conditions"]]
    for formula in formulas.values():
        expressions.append((formula["expression"], formula["bindings"]))
    assert expressions
    for expression, bound in expressions:
        assert "'" not in expression and '"' not in expression, expression
        for match in _tokens(expression, bound):
            name = bound[match.group(1)]
            if name.startswith("formula://"):
                continue
            if not _labelled(channels, name):
                continue
            after = expression[match.end() :]
            before = expression[: match.start()]
            compared = re.match(r"\s*==\s*\d+\b", after)
            # A flag product or count: an index form flag reads 1 while on.
            combined = re.match(r"(\*|\+|$|\))", after) and re.search(r"(^|1-|\*|\+|\()$", before)
            assert compared or combined, (expression, name)


