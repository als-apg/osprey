"""The control-assistant template's booster screen, ``br/overview``.

Generated by ``scripts/facility_demo/facility_overview.py`` from the example
facility's records and opened by the landing page's Booster button and strip
tile: the booster ring with its BPM dots, the dipole and quadrupole ramp LEDs,
the two septa and the kicker, and the booster DCCT with its unit.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest
import yaml
from canopy_mcp import screens
from canopy_mcp.check.lint import served_roles
from canopy_mcp.check.schema import check_schema, schema_path
from canopy_mcp.check.semantic import check_semantic
from canopy_mcp.store import DraftStore

ROOT = Path(__file__).resolve().parents[3]
LIBRARY = (
    ROOT
    / "src"
    / "osprey"
    / "templates"
    / "apps"
    / "control_assistant"
    / "data"
    / "canopy"
    / "library"
)
EXAMPLE_CHANNELS = (
    ROOT / "src" / "osprey" / "templates" / "facilities" / "example" / "records" / "channels.yaml"
)
SCREEN = LIBRARY / "screens" / "br" / "overview.screen.json"
DRAFT_ID = "br/overview"

STATUS_LEDS = [
    "BR:MAG:DIPOLE-RAMP:01:STATUS:ON",
    "BR:MAG:QF-RAMP:01:STATUS:ON",
    "BR:MAG:QD-RAMP:01:STATUS:ON",
    "BR:MAG:SEPTUM:01:STATUS:ON",
    "BR:MAG:SEPTUM:02:STATUS:ON",
    "BR:MAG:KICKER:01:STATUS:ON",
    "BR:DIAG:DCCT:01:STATUS:VALID",
]
COLOUR_PROPS = {
    "absolute-canvas": ("backgroundColor",),
    "text-label": ("foregroundColor", "backgroundColor"),
    "pv-label": ("foregroundColor", "backgroundColor"),
    "pv-led": ("onColor", "offColor"),
    "rectangle": ("lineColor", "fillColor"),
    "line": ("lineColor",),
    "group-box": (),
}
HEX = re.compile(r"^#[0-9a-fA-F]{3,8}$")


@pytest.fixture(scope="module")
def doc() -> dict:
    return json.loads(SCREEN.read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def nodes(doc: dict) -> list[dict]:
    return list(_nodes(doc["root"]))


@pytest.fixture(scope="module")
def channels() -> dict:
    records = yaml.safe_load(EXAMPLE_CHANNELS.read_text(encoding="utf-8"))
    return {record["id"]: record for record in records}


def _nodes(node: dict):
    yield node
    for child in node.get("children", []):
        yield from _nodes(child)


def _roles(value: object):
    if isinstance(value, dict):
        if "$role" in value:
            yield value
            return
        for item in value.values():
            yield from _roles(item)
    elif isinstance(value, list):
        for item in value:
            yield from _roles(item)


def _bare_hex(value: object):
    if isinstance(value, dict):
        if "$role" not in value:
            for item in value.values():
                yield from _bare_hex(item)
    elif isinstance(value, list):
        for item in value:
            yield from _bare_hex(item)
    elif isinstance(value, str) and HEX.match(value):
        yield value


@pytest.fixture
def spec_dir(tmp_path: Path) -> Path:
    from importlib.resources import files

    source = files("pydmconverter.ir").joinpath("data", "screen-ir.schema.json")
    target = schema_path(tmp_path / "spec", "1.1")
    target.parent.mkdir(parents=True)
    target.write_bytes(source.read_bytes())
    return tmp_path / "spec"


def test_the_screen_validates_and_passes_the_semantic_check(doc: dict, spec_dir: Path) -> None:
    assert check_schema(doc, spec_dir) == []
    assert check_semantic(doc) == []
    assert doc["id"] == DRAFT_ID
    assert doc["metadata"]["title"] == "Booster"


def test_the_file_is_generated_canonical_ascii_json(doc: dict) -> None:
    assert SCREEN.read_text(encoding="utf-8") == json.dumps(doc, indent=2, ensure_ascii=True) + "\n"


def test_it_binds_the_ring_bpms_ramps_septa_kicker_and_dcct(doc: dict, channels: dict) -> None:
    pvs = screens.expanded_pvs(doc, DraftStore(LIBRARY), DRAFT_ID)
    bpms = [f"BR:DIAG:BPM:{i:02d}:STATUS:VALID" for i in range(1, 9)]
    assert sorted(pvs) == sorted([*bpms, *STATUS_LEDS, "BR:DIAG:DCCT:01:CURRENT:RB"])
    assert all(name in channels for name in pvs)


def test_the_leds_in_device_order(nodes: list[dict]) -> None:
    leds = [n["props"]["pv"] for n in nodes if n["type"] == "pv-led"]
    assert leds == [f"BR:DIAG:BPM:{i:02d}:STATUS:VALID" for i in range(1, 9)] + STATUS_LEDS


def test_the_dcct_reads_with_its_unit(nodes: list[dict], channels: dict) -> None:
    [field] = [n for n in nodes if n["type"] == "pv-label"]
    assert field["props"]["pv"] == "BR:DIAG:DCCT:01:CURRENT:RB"
    assert field["props"]["showUnits"] is True
    assert channels["BR:DIAG:DCCT:01:CURRENT:RB"]["unit"] == "mA"


def test_the_ring_sketch_draws_one_symbol_per_booster_magnet(
    nodes: list[dict], channels: dict
) -> None:
    magnets = {
        tuple(name.split(":")[2:4])
        for name in channels
        if re.match(r"BR:MAG:(DIPOLE|QF|QD):\d+:", name)
    }
    symbols = [
        n
        for n in nodes
        if n["type"] == "rectangle" and n["props"]["fillColor"]["$role"] in ("Dipole", "Quadrupole")
    ]
    assert len(symbols) == len(magnets) == 16
    assert len([n for n in nodes if n["type"] == "line"]) == 1


def test_no_buttons_and_every_widget_inside_the_canvas(doc: dict, nodes: list[dict]) -> None:
    root = doc["root"]
    assert not [n for n in nodes if n["props"].get("actions")]
    for n in nodes[1:]:
        g = n["geometry"]
        assert g["x"] >= 0 and g["y"] >= 0, n["id"]
        assert g["x"] + g["width"] <= root["geometry"]["width"], n["id"]
        assert g["y"] + g["height"] <= root["geometry"]["height"], n["id"]


def test_no_two_groups_overlap(nodes: list[dict]) -> None:
    groups = [n["geometry"] for n in nodes if n["type"] == "group-box"]
    assert len(groups) == 3
    for i, a in enumerate(groups):
        for b in groups[i + 1 :]:
            assert a["y"] + a["height"] <= b["y"] or b["y"] + b["height"] <= a["y"]


def test_every_colour_is_a_custom_role_with_both_fallbacks(doc: dict, nodes: list[dict]) -> None:
    for n in nodes:
        for prop in COLOUR_PROPS[n["type"]]:
            value = n["props"][prop]
            assert {"$role", "fallback", "fallbackDark"} <= set(value), (n["id"], prop)
    used = {role["$role"] for role in _roles(doc)}
    assert used.isdisjoint(served_roles())
    assert list(_bare_hex(doc)) == []
