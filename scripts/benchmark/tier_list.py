#!/usr/bin/env python3
"""Write the docs page's per-tier test list from the tests' ``agentic`` markers.

The list is generated, never hand-written: it is the board's run set, read from live
collection the way a cell reads it (``check_e2e_coverage.run_args`` and the
``OSPREY_E2E_LANES`` manifest), with the same title, ask and pass condition the
dashboard shows. ``--check`` exits 1 when the checked-in fragment differs.

    scripts/benchmark/tier_list.py            # rewrite the fragment
    scripts/benchmark/tier_list.py --check    # fail if it is stale
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
FRAGMENT = REPO / "docs/source/how-to/llm-providers/agentic-tests.rst.inc"
CONFIG = REPO / "scripts/benchmark/matrix_e2e_config.json"
TIER_NAMES = {1: "Tier 1", 2: "Tier 2"}


def _run_args() -> list[str]:
    spec = importlib.util.spec_from_file_location(
        "benchmark_check_e2e_coverage", Path(__file__).with_name("check_e2e_coverage.py")
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    excluded = {e["path"]: e["reason"] for e in json.loads(CONFIG.read_text())["excluded_files"]}
    return module.run_args(excluded)


def board_tests() -> list[dict]:
    """Every test a board cell runs, with its marker's tier and text."""
    with tempfile.TemporaryDirectory() as tmp:
        manifest = Path(tmp) / "lanes.json"
        proc = subprocess.run(
            [sys.executable, "-m", "pytest", "tests/e2e/", "--collect-only", "-q"]
            + ["-p", "no:cacheprovider", "-o", "addopts=", "--assert=plain", *_run_args()],
            cwd=REPO,
            env={**os.environ, "OSPREY_E2E_LANES": str(manifest)},
            capture_output=True,
            text=True,
        )
        if proc.returncode != 0:
            raise SystemExit(f"collection failed (rc={proc.returncode}):\n{proc.stdout[-800:]}")
        entries = json.loads(manifest.read_text())
    return [e for e in entries.values() if e.get("lane") == "agentic"]


def _escape(text: str) -> str:
    for char in ("\\", "*", "`", "|"):
        text = text.replace(char, "\\" + char)
    return text


def render(tests: list[dict]) -> str:
    """The fragment: one collapsed section per tier, a test per entry."""
    lines = [
        ".. Generated by scripts/benchmark/tier_list.py from the tests' agentic markers;",
        "   do not edit. tests/benchmark/test_matrix_lanes.py fails when it is stale.",
        "",
    ]
    for tier, name in TIER_NAMES.items():
        in_tier = sorted((t for t in tests if t["tier"] == tier), key=lambda t: t["title"])
        lines += [f".. dropdown:: {name} · {len(in_tier)} tests", ""]
        for test in in_tier:
            lines += [
                f"   **{_escape(test['title'])}**",
                f"      | *Asks:* {_escape(test['asks'])}",
                f"      | *Passes if:* {_escape(test['passes_if'])}",
                "",
            ]
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the fragment is stale")
    args = ap.parse_args(argv)
    text = render(board_tests())
    if args.check:
        if FRAGMENT.read_text(encoding="utf-8") != text:
            print(
                f"{FRAGMENT.relative_to(REPO)} is stale: run {Path(__file__).name}", file=sys.stderr
            )
            return 1
        return 0
    FRAGMENT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
